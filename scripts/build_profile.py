"""Generate the profile SVGs and compose README.md."""

from build_banner import build_banner
from build_projects import build_project_card
from build_stack import build_stack
from theme import ASSETS, PROJECTS, ROOT, SNAKE_URL, THEMES


README_TEMPLATE = """<!-- Generated by scripts/build_profile.py; edit the source in scripts/ instead. -->
<p align="center">
  <picture>
    <source media="(prefers-color-scheme: dark)" srcset="assets/banner-dark.svg">
    <source media="(prefers-color-scheme: light)" srcset="assets/banner-light.svg">
    <img src="assets/banner-light.svg" width="100%" alt="Saad Alam — Web Developer and AI Automation Engineer">
  </picture>
</p>

<p align="center">
  <a href="https://github.com/alamzweb">GitHub</a> &nbsp;·&nbsp;
  <a href="https://x.com/msaad_alam">X</a> &nbsp;·&nbsp;
  <a href="mailto:contact@dnnengineer.com">Email</a>
</p>

## About

I build practical web products, websites, and automation workflows — from the first idea through launch.

## Selected work

{project_grid}

## Technology

<!-- Generated technology icon grid; edit the catalog in scripts/theme.py. -->
<!-- TECHNOLOGY_STACK_START -->
{technology_stack}
<!-- TECHNOLOGY_STACK_END -->

---

<p align="center">
  <a href="https://x.com/msaad_alam">Connect on X</a> &nbsp;·&nbsp;
  <a href="mailto:contact@dnnengineer.com">Contact by email</a>
</p>

<p align="center">
  <img src="{snake_url}" alt="GitHub contribution snake animation" width="100%">
</p>
"""


def main() -> None:
    ASSETS.mkdir(parents=True, exist_ok=True)
    for theme_name in THEMES:
        (ASSETS / f"banner-{theme_name}.svg").write_text(
            build_banner(theme_name), encoding="utf-8"
        )
        for project in PROJECTS:
            slug = project.name.lower()
            (ASSETS / f"{slug}-card-{theme_name}.svg").write_text(
                build_project_card(project, theme_name), encoding="utf-8"
            )

    readme = README_TEMPLATE.format(
        technology_stack=build_stack(),
        project_grid=build_project_grid(),
        snake_url=SNAKE_URL,
    )
    (ROOT / "README.md").write_text(readme, encoding="utf-8")
    print("Generated README.md, banner SVGs, and project card SVGs.")


def build_project_grid() -> str:
    rows = []
    for row_start in range(0, len(PROJECTS), 2):
        cells = []
        for project in PROJECTS[row_start : row_start + 2]:
            slug = project.name.lower()
            title = project.name
            picture = f"""<a href="{project.url}">
  <picture>
    <source media="(prefers-color-scheme: dark)" srcset="assets/{slug}-card-dark.svg">
    <source media="(prefers-color-scheme: light)" srcset="assets/{slug}-card-light.svg">
    <img src="assets/{slug}-card-light.svg" width="100%" alt="{title}: {project.description}">
  </picture>
</a>"""
            cells.append(f"<td width=\"50%\" valign=\"top\">\n{picture}\n</td>")
        rows.append(f"<tr>\n{chr(10).join(cells)}\n</tr>")
    return (
        '<table width="100%">\n'
        f"{chr(10).join(rows)}\n"
        "</table>"
    )


if __name__ == "__main__":
    main()
